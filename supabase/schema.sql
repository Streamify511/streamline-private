-- Run once in Supabase Dashboard > SQL Editor.
-- The app uses the publishable/anon key only. Row Level Security enforces ownership.

create table if not exists public.series (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (length(trim(title)) > 0),
  description text not null default '',
  category text not null default '',
  cover_path text,
  created_at timestamptz not null default now(),
  unique (id, owner_id)
);

create table if not exists public.episodes (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  series_id bigint,
  title text not null check (length(trim(title)) > 0),
  description text not null default '',
  storage_path text not null unique,
  size_bytes bigint not null check (size_bytes > 0),
  duration double precision not null default 0,
  thumbnail_path text,
  created_at timestamptz not null default now(),
  unique (id, owner_id),
  foreign key (series_id, owner_id) references public.series(id, owner_id) on delete cascade
);

-- Safe to rerun on an existing project when adding episode thumbnails.
alter table public.episodes add column if not exists thumbnail_path text;

create table if not exists public.playback_progress (
  owner_id uuid not null references auth.users(id) on delete cascade,
  episode_id bigint not null,
  position double precision not null default 0 check (position >= 0),
  duration double precision not null default 0 check (duration >= 0),
  completed boolean not null default false,
  updated_at timestamptz not null default now(),
  primary key (owner_id, episode_id),
  foreign key (episode_id, owner_id) references public.episodes(id, owner_id) on delete cascade
);

create table if not exists public.library_flags (
  owner_id uuid not null references auth.users(id) on delete cascade,
  episode_id bigint not null,
  kind text not null check (kind in ('favorite', 'watchlist')),
  created_at timestamptz not null default now(),
  primary key (owner_id, episode_id, kind),
  foreign key (episode_id, owner_id) references public.episodes(id, owner_id) on delete cascade
);

create index if not exists episodes_owner_created_idx on public.episodes(owner_id, created_at desc);
create index if not exists episodes_series_idx on public.episodes(series_id);
create index if not exists progress_recent_idx on public.playback_progress(owner_id, updated_at desc);

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.series, public.episodes,
  public.playback_progress, public.library_flags to authenticated;
grant usage, select on all sequences in schema public to authenticated;

alter table public.series enable row level security;
alter table public.episodes enable row level security;
alter table public.playback_progress enable row level security;
alter table public.library_flags enable row level security;

drop policy if exists "Own series only" on public.series;
create policy "Own series only" on public.series for all to authenticated
  using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()));
drop policy if exists "Own episodes only" on public.episodes;
create policy "Own episodes only" on public.episodes for all to authenticated
  using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()));
drop policy if exists "Own progress only" on public.playback_progress;
create policy "Own progress only" on public.playback_progress for all to authenticated
  using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()));
drop policy if exists "Own flags only" on public.library_flags;
create policy "Own flags only" on public.library_flags for all to authenticated
  using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()));

